/* A negative ratio would index before gAcosLutQ11; both callers (stage_moat.c) pass one between 0 and ONE. */
int ComputeAcosQ12(int ratio)
{
    int angle;

    if (ratio <= ONE) {
        angle = gAcosLutQ11[ratio >> 1];
    } else {
        angle = 0;
    }
    return angle;
}

/* Nothing calls it. It indexes gAcosLutQ11 by a Q12 ratio, past the table's end for ratios above 1/2. */
static short ComputeAcosRatio(int whole, int part)
{
    unsigned short *table;
    int angle;

    part = (part << 12) / whole;
    table = (unsigned short *)gAcosLutQ11;
    angle = *(part >= 0 ? table + part : table - part);
    if (part < 0)
        angle = ANGLE_HALF - angle;

    return angle;
}

/* Nothing calls it. It indexes gAcosLutQ11 by one minus a Q12 ratio, past the table's end for ratios below 1/2. */
static int ComputeAcosComplementRatio(int whole, int part)
{
    return gAcosLutQ11[ONE - (part * ONE) / whole];
}

void UpdateNodeWorldMatrix(struct SceneNode *node)
{
    SVECTOR translation;
    long flag;

    if (node->matrixState == SCENE_MATRIX_WORLD_VALID)
        return;

    if (node->matrixState != SCENE_MATRIX_LOCAL_PRECOMPUTED)
        gRotMatrixBuilders[node->rotOrder](&node->rotation, &node->localMatrix);

    if (node->parent != 0) {
        if (node->parent->matrixState == SCENE_MATRIX_DIRTY)
            UpdateNodeWorldMatrix(node->parent);
        MulMatrix3x3Fast(&node->parent->worldMatrix, &node->localMatrix, &node->worldMatrix);
        SetRotMatrix(&node->parent->worldMatrix);
        SetTransMatrix(&node->parent->worldMatrix);
        translation.vx = node->localMatrix.t[0];
        translation.vy = node->localMatrix.t[1];
        translation.vz = node->localMatrix.t[2];
        RotTrans(&translation, (VECTOR *)node->worldMatrix.t, &flag);
    } else {
        node->worldMatrix = node->localMatrix;
    }

    node->matrixState = SCENE_MATRIX_WORLD_VALID;
}

void BuildNegatedNodeRotation(struct SceneNode *node)
{
    SVECTOR negatedRotation;

    negatedRotation.vx = -node->rotation.vx;
    negatedRotation.vy = -node->rotation.vy;
    negatedRotation.vz = -node->rotation.vz;
    gRotMatrixBuilders[node->rotOrder](&negatedRotation, &node->localMatrix);
    node->worldMatrix = node->localMatrix;
}

