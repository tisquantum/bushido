int gBgmTrackSectorCounts[4] = { 16762, 18938, 18825, 24487 };

int StartXaTrack(int track)
{
    int handle;

    handle = ResolveCdFileHandle(CD_CATEGORY_XA, track >> 2);
    if (StartCdAudioStream(handle, track & 3) != 0) {
        if (track >= XA_TRACK_VS_BGM_A) {
            gCdDrive.stream.endSector =
                CdPosToInt(&gCdFileTable[gCdDrive.stream.handle].location) +
                gBgmTrackSectorCounts[track - XA_TRACK_VS_BGM_A];
        }
        return 1;
    }
    return 0;
}

int CueXaTrackPaused(int track)
{
    int cued;

    if (StartXaTrack(track) == 0) {
        cued = 0;
    } else {
        gCdDrive.stream.hold = 1;
        cued = 1;
    }
    return cued;
}

void SetCdAudioRepeat(int repeat)
{
    gCdDrive.stream.repeat = repeat;
}

/* Nothing calls it. */
int CueCdStreamPaused(int handle, int channel)
{
    int cued;

    if (StartCdAudioStream(handle, channel) == 0) {
        cued = 0;
    } else {
        gCdDrive.stream.hold = 1;
        cued = 1;
    }
    return cued;
}

void StopCdAudioStream(void)
{
    gCdDrive.stream.hold = 0;
    gCdDrive.stream.stopRequested = 1;
}

void ReleaseHeldCdStream(void)
{
    gCdDrive.stream.hold = 0;
}

void WaitCdStreamPlaying(void)
{
    while (gCdDrive.stream.state != CD_STREAM_AUDIO_POLL_WAIT) {
        ExchangeIdleLinkPacket();
        UpdateCdSubsystem();
        VSync(2);
    }
}

int StopAndWaitCdIdle(void)
{
    int result;

    if (gLinkSyncPhase == 0) {
        BeginLinkSyncPause();
        if (gCdDrive.stream.state != CD_STREAM_IDLE) {
            AbortCdOperation();
        }
        WaitCdIdle();
        result = WaitLinkSyncBarrier();
    } else {
        if (gCdDrive.stream.state != CD_STREAM_IDLE) {
            AbortCdOperation();
        }
        result = WaitCdIdle();
    }
    return result;
}
