CdlATV gCdMixCurrent;
short gCdMixFadeLength; /* frames; only StartCdAudioMixFade, which nothing calls, sets it above 0 */

void SetCdAudioMix(int ll, int lr, int rl, int rr)
{
    gCdMixCurrent.val0 = ll;
    gCdMixCurrent.val1 = lr;
    gCdMixCurrent.val2 = rl;
    gCdMixCurrent.val3 = rr;
    CdMix(&gCdMixCurrent);
    gCdMixFadeLength = 0;
}

CdlATV gCdMixTarget;
short gCdMixFadeTick;

/* Nothing calls it. */
void StartCdAudioMixFade(int length, int ll, int lr, int rl, int rr)
{
    gCdMixTarget.val0 = ll;
    gCdMixTarget.val1 = lr;
    gCdMixTarget.val2 = rl;
    gCdMixTarget.val3 = rr;
    gCdMixFadeLength = length;
    gCdMixFadeTick = 0;
}

void EnableCdSpuAudio(void)
{
    SsSetSerialAttr(SS_SERIAL_A, SS_MIX, SS_SON);
    SsSetSerialVol(SS_SERIAL_A, 0x7f, 0x7f);
}

void InitCdSubsystem(void)
{
    CdInit();
    CdSetDebug(0);
    SetCdAudioMix(0, 0, 0, 0);
    gCdDrive.stream.state = CD_STREAM_IDLE;
}

static void HandleCdDataReadyIrq(u_char event, u_char *response)
{
    u_char header[12];

    if (event == CdlDataReady) {
        gCdDrive.stream.readWait = 0;
        if (gCdDrive.stream.sectorsLeft <= 0)
            return;

        CdGetSector(header, sizeof(header) / 4);
        if (CdPosToInt((CdlLOC *)header) != gCdDrive.stream.expectedSector) {
            gCdDrive.stream.sectorsLeft = -2;
        } else {
            CdGetSector(gCdDrive.stream.readCursor, CD_SECTOR_SIZE / 4);
            gCdDrive.stream.readCursor += CD_SECTOR_SIZE;
            --gCdDrive.stream.sectorsLeft;
            ++gCdDrive.stream.expectedSector;
            if (gCdDrive.stream.sectorsLeft != 0)
                return;
        }
    } else {
        gCdDrive.stream.sectorsLeft = -1;
    }
    CdReadyCallback(0);
    CdControlF(CdlPause, 0);
}

/* The drive's reply. A CD audio report holds status, track, index, then minute, second and sector;
 * bit 7 of the second marks a time within the track rather than on the disc. */
u_char result[8];

u_char gXaTrackVolumes[4][XA_CHANNELS_PER_FILE] = {
    { 0x70, 0x70, 0x70, 0x70 },
    { 0x70, 0x70, 0x70, 0x70 },
    { 0x70, 0x70, 0x7f, 0x7f },
    { 0x70, 0x78, 0x78, 0x78 },
};

static void UpdateCdAudioStream(void)
{
    CdlATV mix;
    short length, tick;
    int targetLL, remain;
    int ll, lr, rl, rr;
    int status;

    length = gCdMixFadeLength;
    if (length > 0) {
        targetLL = gCdMixTarget.val0;
        tick = gCdMixFadeTick;
        remain = length - tick;
        ll = (targetLL * tick + gCdMixCurrent.val0 * remain) / length;
        lr = (gCdMixTarget.val1 * tick + gCdMixCurrent.val1 * remain) / length;
        rl = (gCdMixTarget.val2 * tick + gCdMixCurrent.val2 * remain) / length;
        rr = (gCdMixTarget.val3 * tick + gCdMixCurrent.val3 * remain) / length;
        mix.val0 = ll;
        mix.val1 = lr;
        mix.val2 = rl;
        mix.val3 = rr;
        CdMix(&mix);
        tick = ++gCdMixFadeTick;
        if (tick >= gCdMixFadeLength) {
            gCdMixFadeLength = 0;
            gCdMixCurrent = gCdMixTarget;
        }
    }

    switch (gCdDrive.stream.state) {
    case CD_STREAM_AUDIO_SETMODE:
        SetCdAudioMix(0, 0, 0, 0);
        CdControlF(CdlSetmode, gCdDrive.stream.mode);
        gCdDrive.stream.ticks = 0;
        gCdDrive.stream.delay = 0;
        gCdDrive.stream.endCountdown = 0;
        gCdDrive.stream.state = CD_STREAM_AUDIO_SETMODE_WAIT;
        return;
    case CD_STREAM_AUDIO_SETMODE_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            CdControlF(CdlSetloc, (u_char *)gCdDrive.stream.startLoc);
            gCdDrive.stream.state = CD_STREAM_AUDIO_SEEK;
            return;
        }
        break;
    case CD_STREAM_AUDIO_SEEK:
        if (++gCdDrive.stream.delay < 3)
            return;
        status = CdSync(1, result);
        if (status == CdlComplete) {
            CdControlF(CdlSeekP, 0);
            gCdDrive.stream.state = CD_STREAM_AUDIO_SEEK_WAIT;
            return;
        }
        break;
    case CD_STREAM_AUDIO_SEEK_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            if (gCdDrive.stream.hold != 0)
                return;
            CdControlF(gCdDrive.stream.isXaStream ? CdlReadS : CdlPlay, 0);
            gCdDrive.stream.state = CD_STREAM_AUDIO_PLAY_WAIT;
            return;
        }
        break;
    case CD_STREAM_AUDIO_PLAY_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.readyWait = 0;
            gCdDrive.stream.state = CD_STREAM_AUDIO_POLL;
            return;
        }
        break;
    case CD_STREAM_AUDIO_POLL:
        if (++gCdDrive.stream.ticks == 2 && gCombatPaused == 0) {
            if (gCdDrive.stream.isXaStream) {
                int xaBase = ResolveCdFileHandle(CD_CATEGORY_XA, 0);
                int volume = gXaTrackVolumes[gCdDrive.stream.handle - xaBase][gCdDrive.stream.filter.chan];
                SetCdAudioMix(volume, 0, volume, 0);
            } else {
                SetCdAudioMix(0x7f, 0, 0x7f, 0);
            }
        }
        if (gCdDrive.stream.stopRequested && gCdDrive.stream.ticks >= 5) {
            gCdDrive.stream.state = CD_STREAM_AUDIO_STOP;
            return;
        }

        gCdDrive.stream.state = CD_STREAM_AUDIO_POLL_WAIT;
        if (gCdDrive.stream.isXaStream) {
            CdControlF(CdlGetlocP, result);
            gCdDrive.stream.syncWait = 0;
            return;
        }

        CdControlF(CdlNop, 0);
        status = CdReady(1, result);
        if (status == CdlDataReady) {
            if (!(result[4] & 0x80)) {
                gCdDrive.stream.readyWait = 0;
                if (CdPosToInt((CdlLOC *)(result + 3)) >= gCdDrive.stream.endSector) {
                    SetCdAudioMix(0, 0, 0, 0);
                    gCdDrive.stream.state = gCdDrive.stream.repeat ? CD_STREAM_AUDIO_SETMODE : CD_STREAM_AUDIO_STOP;
                }
            }
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_AUDIO_ERROR;
        }
        if (gCdDrive.stream.readyWait++ >= 61)
            gCdDrive.stream.state = CD_STREAM_AUDIO_ERROR;
        return;
    case CD_STREAM_AUDIO_POLL_WAIT: {
        int sector, endSector;

        if (gCdDrive.stream.endCountdown != 0 && (gCdDrive.stream.endCountdown -= 4) <= 0) {
            SetCdAudioMix(0, 0, 0, 0);
            gCdDrive.stream.state = gCdDrive.stream.repeat ? CD_STREAM_AUDIO_SETMODE : CD_STREAM_AUDIO_STOP;
            return;
        }

        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.state = CD_STREAM_AUDIO_POLL;
            if (gCdDrive.stream.isXaStream) {
                sector = CdPosToInt((CdlLOC *)(result + 5));
                endSector = gCdDrive.stream.endSector;
                if (sector >= endSector) {
                    SetCdAudioMix(0, 0, 0, 0);
                    gCdDrive.stream.state = gCdDrive.stream.repeat ? CD_STREAM_AUDIO_SETMODE : CD_STREAM_AUDIO_STOP;
                } else if (sector >= endSector - 75 && gCdDrive.stream.endCountdown == 0) {
                    gCdDrive.stream.endCountdown = endSector - sector;
                }
            }
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_AUDIO_ERROR;
        } else if (gCdDrive.stream.isXaStream && ++gCdDrive.stream.syncWait >= 31) {
            CdFlush();
            gCdDrive.stream.state = CD_STREAM_AUDIO_POLL;
        }
        return;
    }
    case CD_STREAM_AUDIO_STOP:
        SetCdAudioMix(0, 0, 0, 0);
        CdControlF(CdlPause, 0);
        gCdDrive.stream.state = CD_STREAM_AUDIO_STOP_WAIT;
        return;
    case CD_STREAM_AUDIO_STOP_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.ticks = 0;
            gCdDrive.stream.state = CD_STREAM_AUDIO_COOLDOWN;
            return;
        }
        break;
    case CD_STREAM_AUDIO_COOLDOWN:
        if (++gCdDrive.stream.ticks >= 5)
            gCdDrive.stream.state = CD_STREAM_IDLE;
        return;
    case CD_STREAM_AUDIO_ERROR:
        SetCdAudioMix(0, 0, 0, 0);
        if (result[0] & CdlStatShellOpen)
            gCdDrive.stream.state = CD_STREAM_AUDIO_NOP;
        else
            gCdDrive.stream.state = CD_STREAM_AUDIO_GET_TN;
        return;
    case CD_STREAM_AUDIO_NOP:
        CdControlF(CdlNop, 0);
        gCdDrive.stream.state = CD_STREAM_AUDIO_NOP_WAIT;
        return;
    case CD_STREAM_AUDIO_NOP_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            if (result[0] & CdlStatShellOpen)
                gCdDrive.stream.state = CD_STREAM_AUDIO_NOP;
            else
                gCdDrive.stream.state = CD_STREAM_AUDIO_GET_TN;
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_AUDIO_NOP;
        }
        return;
    case CD_STREAM_AUDIO_GET_TN:
        CdControlF(CdlGetTN, 0);
        gCdDrive.stream.state = CD_STREAM_AUDIO_GET_TN_WAIT;
        return;
    case CD_STREAM_AUDIO_GET_TN_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.state = gCdDrive.stream.stopRequested ? CD_STREAM_IDLE : CD_STREAM_AUDIO_SETMODE;
            return;
        }
        break;
    default:
        return;
    }

    if (status == CdlDiskError)
        gCdDrive.stream.state = CD_STREAM_AUDIO_ERROR;
}

void UpdateCdSubsystem(void)
{
    u_char mode;
    int status;

    if (gCdDrive.stream.state >= CD_STREAM_AUDIO_SETMODE) {
        UpdateCdAudioStream();
        return;
    }
    switch (gCdDrive.stream.state) {
    case CD_STREAM_IDLE:
        break;
    case CD_STREAM_READ_SETMODE:
        if (gCdDrive.stream.stopRequested != 0) {
            gCdDrive.stream.state = CD_STREAM_IDLE;
            break;
        }
        mode = CdlModeSpeed | CdlModeSize1;
        CdControlF(CdlSetmode, &mode);
        gCdDrive.stream.unreadWord = 0;
        gCdDrive.stream.readWait = 0;
        gCdDrive.stream.state = CD_STREAM_READ_SETMODE_WAIT;
        break;
    case CD_STREAM_READ_DONE:
        gCdDrive.stream.state = CD_STREAM_IDLE;
        break;
    case CD_STREAM_READ_SETMODE_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.state = CD_STREAM_READ_SEEK_DELAY;
            gCdDrive.stream.delay = 0;
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_READ_ERROR;
        } else if (++gCdDrive.stream.readWait > 60) {
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        }
        break;
    case CD_STREAM_READ_SEEK_DELAY:
        if (++gCdDrive.stream.delay >= 3) {
            gCdDrive.stream.readCursor = gCdDrive.stream.dest;
            gCdDrive.stream.sectorsLeft = gCdDrive.stream.sectorCount;
            gCdDrive.stream.expectedSector = CdPosToInt(gCdDrive.stream.startLoc);
            CdControl(CdlSetloc, (u_char *)gCdDrive.stream.startLoc, 0);
            gCdDrive.stream.readWait = 0;
            gCdDrive.stream.state = CD_STREAM_READ_START;
        }
        break;
    case CD_STREAM_READ_START:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.readWait = 0;
            CdReadyCallback(HandleCdDataReadyIrq);
            CdControlF(CdlReadN, (u_char *)gCdDrive.stream.startLoc);
            gCdDrive.stream.state = CD_STREAM_READ_ACTIVE;
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_READ_ERROR;
        } else if (++gCdDrive.stream.readWait > 60) {
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        }
        break;
    case CD_STREAM_READ_ACTIVE:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            if (gCdDrive.stream.sectorsLeft == 0) {
                gCdDrive.stream.state = CD_STREAM_READ_DONE;
            } else if (gCdDrive.stream.sectorsLeft < 0) {
                gCdDrive.stream.state = CD_STREAM_READ_ERROR;
            } else if (++gCdDrive.stream.readWait > 60) {
                CdReadyCallback(0);
                gCdDrive.stream.state = CD_STREAM_READ_NOP;
            }
        } else if (status == CdlDiskError) {
            CdReadyCallback(0);
            gCdDrive.stream.state = CD_STREAM_READ_ERROR;
        } else if (++gCdDrive.stream.readWait > 60) {
            CdReadyCallback(0);
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        }
        break;
    case CD_STREAM_READ_ERROR:
        if (result[0] & CdlStatShellOpen)
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        else
            gCdDrive.stream.state = CD_STREAM_READ_GET_TN;
        break;
    case CD_STREAM_READ_NOP:
        CdControlF(CdlNop, 0);
        gCdDrive.stream.state = CD_STREAM_READ_NOP_WAIT;
        gCdDrive.stream.retryWait = 0;
        break;
    case CD_STREAM_READ_NOP_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            if (result[0] & CdlStatShellOpen)
                gCdDrive.stream.state = CD_STREAM_READ_NOP;
            else
                gCdDrive.stream.state = CD_STREAM_READ_GET_TN;
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        } else if (++gCdDrive.stream.retryWait > 10) {
            CdFlush();
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        }
        break;
    case CD_STREAM_READ_GET_TN:
        CdControlF(CdlGetTN, 0);
        gCdDrive.stream.state = CD_STREAM_READ_GET_TN_WAIT;
        gCdDrive.stream.retryWait = 0;
        break;
    case CD_STREAM_READ_GET_TN_WAIT:
        status = CdSync(1, result);
        if (status == CdlComplete) {
            gCdDrive.stream.state = CD_STREAM_READ_SETMODE;
        } else if (status == CdlDiskError) {
            gCdDrive.stream.state = CD_STREAM_READ_ERROR;
        } else if (++gCdDrive.stream.retryWait > 30) {
            CdFlush();
            gCdDrive.stream.state = CD_STREAM_READ_NOP;
        }
        break;
    }
}

int IsCdIdle(void)
{
    return gCdDrive.stream.state == CD_STREAM_IDLE;
}

