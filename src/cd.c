int StartCdFileRead(int handle, void *buffer)
{
    CdFileEntry *file;
    unsigned int size;

    if (gCdDrive.stream.state != CD_STREAM_IDLE)
        return 0;

    file = &gCdFileTable[(short)handle];
    gCdDrive.stream.handle = handle;
    gCdDrive.stream.startLoc = &file->location;
    gCdDrive.stream.dest = buffer;
    size = file->size;
    gCdDrive.stream.stopRequested = 0;
    gCdDrive.stream.state = CD_STREAM_READ_SETMODE;
    gCdDrive.stream.sectorCount = (size + CD_SECTOR_SIZE - 1) / CD_SECTOR_SIZE;
    return 1;
}

int ResolveCdFileHandle(int category, int index)
{
    return gCdCategoryFirstFile[category] + index;
}

static void AbortCdOperation(void)
{
    CdReadyCallback(0);
    SetCdAudioMix(0, 0, 0, 0);
    CdFlush();
    CdControlF(CdlPause, 0);
    gCdDrive.stream.stopRequested = 1;
    gCdDrive.stream.state = CD_STREAM_READ_NOP_WAIT;
    gCdDrive.stream.retryWait = 0;
}

/* Nothing calls it. */
int GetCdFileSize(int handle)
{
    return gCdFileTable[handle].size;
}

int WaitCdIdle(void)
{
    int idle;

    while ((idle = IsCdIdle()) == 0) {
        ExchangeIdleLinkPacket();
        UpdateCdSubsystem();
        VSync(2);
    }
    return idle;
}

static int StartCdAudioStream(int handle, int channel)
{
    CdlLOC *startLoc;
    int startSector;

    if (gCdDrive.stream.state != CD_STREAM_IDLE)
        return 0;

    startLoc = &gCdFileTable[(short)handle].location;
    gCdDrive.stream.handle = handle;
    gCdDrive.stream.startLoc = startLoc;
    startSector = CdPosToInt(startLoc);
    gCdDrive.stream.endSector = startSector + (gCdFileTable[gCdDrive.stream.handle].size / CD_SECTOR_SIZE) - 150;

    if (channel < 0) {
        gCdDrive.stream.isXaStream = 0;
        gCdDrive.stream.mode[0] = CdlModeRept | CdlModeDA;
    } else {
        gCdDrive.stream.isXaStream = 1;
        gCdDrive.stream.filter.file = 1;
        gCdDrive.stream.filter.chan = channel;
        CdControlB(CdlSetfilter, (u_char *)&gCdDrive.stream.filter, 0);
        gCdDrive.stream.mode[0] = CdlModeRT | CdlModeSF | CdlModeDA;
    }

    gCdDrive.stream.hold = 0;
    gCdDrive.stream.stopRequested = 0;
    gCdDrive.stream.repeat = 0;
    gCdDrive.stream.state = CD_STREAM_AUDIO_SETMODE;
    return 1;
}

