unsigned short note2pitch(void)
{
    short diff;
    short octave;
    short semitone;
    short octave_shift;
    unsigned short fine_step;
    unsigned short pitch;

    diff = _svm_cur.note + 60 - _svm_cur.tone_center;
    octave = diff / 12;
    semitone = diff % 12;
    fine_step = _svm_cur.tone_shift / 8;
    if (fine_step >= 16) {
        fine_step = 15;
    }
    pitch = pitch_table[fine_step + (semitone << 4)];
    octave_shift = octave - 5;
    if (octave_shift > 0) {
        pitch <<= octave_shift;
    } else if (octave_shift < 0) {
        pitch >>= -octave_shift;
    }
    return pitch;
}

unsigned short note2pitch2(unsigned short note, unsigned short fine)
{
    VagAtr *tone;
    short diff;
    short octave;
    short semitone;
    short octave_shift;
    short fine_step;
    short carry;
    unsigned short pitch;

    tone = &_svm_tn[_svm_cur.tone + _svm_cur.prog_index * VAB_TONES_PER_PROG];
    fine_step = (fine + tone->shift) / 8;
    carry = 0;
    if (fine_step >= 16) {
        carry = 1;
        fine_step -= 16;
    }
    diff = note + 60 - tone->center + carry;
    octave = diff / 12;
    semitone = diff % 12;
    pitch = pitch_table[(semitone << 4) + fine_step];
    octave_shift = octave - 5;
    if (octave_shift > 0) {
        pitch <<= octave_shift;
    } else if (octave_shift < 0) {
        pitch >>= -octave_shift;
    }
    return pitch;
}
